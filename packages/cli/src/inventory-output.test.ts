import type { PersonalDataInventory } from "@bounda-dev/core";
import { describe, expect, it } from "vitest";
import { formatInventory, formatInventoryMarkdown } from "./inventory-output.ts";

const inventory: PersonalDataInventory = {
  categories: [
    { name: "default", basis: null, retention: null, fields: 1 },
    { name: "contact", basis: "consent", retention: "730d", fields: 1 },
  ],
  holders: [
    {
      kind: "process-state",
      name: "order.lifecycle",
      person: null,
      fields: [{ name: "note", category: "default", sealing: "sealed" }],
      stores: ["event-store"],
      database: "sqlite",
    },
    {
      kind: "command",
      name: "order.remind",
      person: "customerId",
      fields: [],
      stores: ["scheduled-commands", "dead-letters"],
      database: "sqlite",
    },
    {
      kind: "read-model",
      name: "customers",
      person: "customerId",
      fields: [
        { name: "email", category: "contact", sealing: "sealed-indexed" },
        { name: "name", category: "default", sealing: "clear" },
      ],
      stores: ["read-model"],
      database: "postgresql",
    },
  ],
  recipients: [
    {
      port: "customer.mailer",
      name: "Mail | Co",
      kind: "processor",
      country: "US",
      safeguard: "standard-contractual-clauses",
      categories: ["contact"],
    },
    {
      port: "customer.crm",
      name: "CRM",
      kind: "joint-controller",
      country: "DE",
      safeguard: null,
      categories: ["contact", "default"],
    },
  ],
  records: [
    { name: "personal-keys", where: "sqlite", keptFor: null },
    { name: "remembered-answers", where: "sqlite", keptFor: "1d" },
    { name: "dead-letters", where: "sqlite", keptFor: "30d" },
    { name: "forget-ledger", where: "forget-ledger", keptFor: "400d" },
    { name: "access-log", where: "app/audit.ts", keptFor: null },
  ],
  notPersonal: [{ kind: "event", name: "order.OrderPlaced", field: "sku" }],
  security: { masterKey: true, tenantKeys: true, forgetLedger: true },
  findings: [{ kind: "no-basis", holder: null, field: null, message: "2 fields have no basis" }],
};

const empty: PersonalDataInventory = {
  categories: [{ name: "default", basis: null, retention: "2y", fields: 0 }],
  holders: [],
  recipients: [],
  records: [{ name: "dead-letters", where: "memory", keptFor: null }],
  notPersonal: [],
  security: { masterKey: false, tenantKeys: false, forgetLedger: false },
  findings: [],
};

describe("formatInventory", () => {
  it("prints every section of the record", () => {
    expect(formatInventory(inventory)).toBe(
      [
        "Personal data inventory (GDPR article 30)",
        "",
        "Categories",
        "  default  no basis declared  kept until forgotten  1 field",
        "  contact  consent  forgotten 730d after last activity  1 field",
        "",
        "Personal data",
        "  process state order.lifecycle, of the instance's id",
        "    note  default  sealed under the person's key",
        "    kept in: event store (sqlite)",
        "  command order.remind, of the person in customerId",
        "    kept in: scheduled commands, dead letters (sqlite)",
        "  read model customers, of the person in customerId",
        "    email  contact  sealed under the person's key, found by a blind index",
        "    name  default  in the clear, forgotten by the read model's projection",
        "    kept in: read-model table (postgresql)",
        "",
        "Recipients",
        "  customer.mailer  Mail | Co, processor in US under standard-contractual-clauses: contact",
        "  customer.crm  CRM, joint-controller in DE: contact, default",
        "",
        "Kept by the runtime",
        "  personal-keys  a key per person and category, wrapped under the tenant's key; until the category is forgotten (sqlite)",
        "  remembered-answers  the answer of each command dispatched with an idempotency key, sealed under its persons; 1d, or until erased by a forgetting (sqlite)",
        "  dead-letters  the payload of each command that gave up, and the error text of failed work, sealed under the persons it names; retried or discarded letters for 30d, failed ones until resolved; unreadable once their person is forgotten (sqlite)",
        "  forget-ledger  each forgetting's person, categories and reason, outside the database; 400d (forget-ledger)",
        "  access-log  every access to personal data, by ids, handed to app/audit.ts; as the app keeps it (app/audit.ts)",
        "",
        "Keys",
        "  master key: named by the configuration",
        "  tenant key store: apart from the database",
        "  forget ledger: a restored backup forgets again",
        "",
        "Declared not personal",
        "  event order.OrderPlaced: sku",
        "",
        "Findings",
        "  2 fields have no basis",
        "1 finding",
      ].join("\n"),
    );
  });

  it("says when nothing is marked, declared or found", () => {
    expect(formatInventory(empty)).toBe(
      [
        "Personal data inventory (GDPR article 30)",
        "",
        "Categories",
        "  default  no basis declared  forgotten 2y after last activity  0 fields",
        "",
        "Personal data",
        "  none marked",
        "",
        "Recipients",
        "  none declared",
        "",
        "Kept by the runtime",
        "  dead-letters  the payload of each command that gave up, and the error text of failed work, sealed under the persons it names; for good once retried or discarded, unreadable once their person is forgotten (memory)",
        "",
        "Keys",
        "  master key: none named",
        "  tenant key store: none named",
        "  forget ledger: none: a restored backup brings back whom it forgot after the copy",
        "",
        "Complete: every field is classified",
      ].join("\n"),
    );
  });
});

